//! Turning a content folder into a container image.
//!
//! The Dockerfile is generated rather than kept in the user's repository. The
//! correct one is not obvious — a base image they did not choose, an install
//! step whose shape depends on which features the content uses, and a runtime
//! stage that must carry the traced application, public assets and runtime content. Getting it slightly wrong yields
//! an image four times the size that still works, so nothing tells you.
//!
//! The Dockerfile is streamed on stdin and the **content folder is the build
//! context**, so generation never changes the authored folder.

use camino::Utf8Path;
use std::io::Write;
use std::process::Stdio;
use zellij_core::features::Features;
use zellij_core::process::CommandExt;
use zellij_core::{Error, Result, delivery::ImagePlatform};

use crate::ContainerEngine;

/// Older distributions can accept `features none` while retaining automatic
/// detection of installed packages. Require the explicit rendering contract.
pub(crate) fn feature_command(features: Features) -> String {
    format!(
        "node -e 'if(require(\"/opt/zellij/package.json\").zellij?.featureSelectionVersion!==1){{console.error(\"This engine does not support explicit feature selection; choose a current ZELLIJ_IMAGE.\");process.exit(2)}}' && node /opt/zellij/bin/zellij.mjs features \"{}\" /app",
        features.as_str()
    )
}

/// The multi-stage build for a site image.
///
/// Kept as one string rather than assembled from parts: a Dockerfile somebody
/// may have to read is worth being able to read here too.
pub fn dockerfile(base: &str, features: Option<Features>) -> String {
    dockerfile_with_options(base, &crate::BuildOptions::with_features(features))
}

pub fn dockerfile_with_options(base: &str, options: &crate::BuildOptions) -> String {
    let feature_step = options
        .features
        .map(|features| {
            format!(
                "\n# Select rendering and dependencies before installation.\nRUN {}\n",
                feature_command(features)
            )
        })
        .unwrap_or_default();
    let overrides = options.docker_environment();
    let guard = options.docker_guard();
    let check = options.docker_check();
    let build_args = zellij_core::build_args::declarations(&options.build_args);

    format!(
        r#"# Generated by `zel image build`. Regenerate rather than edit: this tracks
# the base image, and a copy that stops tracking it stops being correct.
#
# The build context is the content folder itself.

# --------------------------------------------------------------------- build
FROM {base} AS build
{build_args}
WORKDIR /app
ENV ZELLIJ_OUTPUT=standalone
{overrides}{guard}

# Replace the placeholder content wholesale, so a file the image had and yours
# does not cannot survive into your site.
RUN rm -rf /app/content
COPY . /app/content/
{feature_step}
# The base image carries the engine and a manifest and nothing else. This is
# where the manifest becomes an installation — deferred to here because it is
# the first moment the content, and so the features it needs, is known.
RUN npm install --install-links --no-audit --no-fund

# Fails the build on a broken link or an invalid section, naming the file,
# rather than publishing a site with a dead page in it.
{check}

RUN npm run build
RUN node -e "const fs=require('fs'); const {{basePath}}=require('./node_modules/@shebka/zellij/deployment-config.cjs').resolveContentLocation(); fs.writeFileSync('/app/zellij-health-path',encodeURI((basePath||'')+'/'))"

# ------------------------------------------------------------------- runtime
# Trim in a separate stage, then copy its filesystem into a fresh image. A RUN
# deletion in the final image would still download npm/Yarn/headers in old layers.
# Keep Node's matching Alpine libraries, certificates, licenses and shell.
FROM node:24-alpine AS node-runtime
RUN rm -rf /usr/local/lib/node_modules/npm /opt/yarn-v* /usr/local/include/node \
    /usr/local/bin/npm /usr/local/bin/npx /usr/local/bin/yarn /usr/local/bin/yarnpkg \
    && addgroup -g 1001 -S nodejs && adduser -S -u 1001 -G nodejs nextjs

FROM scratch AS runtime
COPY --from=node-runtime / /
{overrides}

ENV PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin \
    NODE_ENV=production \
    NEXT_TELEMETRY_DISABLED=1 \
    PORT=3000 \
    HOSTNAME=0.0.0.0

WORKDIR /app

# `standalone` carries its own traced dependencies, including required
# node_modules. Copy that subset rather than the whole build dependency tree.
COPY --from=build --chown=nextjs:nodejs /app/.next/standalone ./
COPY --from=build --chown=nextjs:nodejs /app/.next/static ./.next/static
COPY --from=build --chown=nextjs:nodejs /app/public ./public
# The catch-all route also loads content for unknown URLs before returning 404.
# Dynamic filesystem reads are not fully captured by Next's dependency tracing.
COPY --from=build --chown=nextjs:nodejs /app/content ./content
COPY --from=build --chown=nextjs:nodejs /app/zellij-health-path ./zellij-health-path

USER nextjs
EXPOSE 3000

HEALTHCHECK --interval=30s --timeout=3s --start-period=5s \
  CMD node -e "fetch('http://127.0.0.1:'+(process.env.PORT||3000)+require('fs').readFileSync('/app/zellij-health-path','utf8')).then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))"

CMD ["node", "server.js"]
"#
    )
}

impl ContainerEngine {
    /// Build a site image from `content`.
    pub fn image_build(
        &self,
        content: &Utf8Path,
        tag: &str,
        features: Option<Features>,
        platform: Option<ImagePlatform>,
    ) -> Result<()> {
        self.image_build_with_options(
            content,
            tag,
            platform,
            &crate::BuildOptions::with_features(features),
        )
    }

    pub fn image_build_with_options(
        &self,
        content: &Utf8Path,
        tag: &str,
        platform: Option<ImagePlatform>,
        options: &crate::BuildOptions,
    ) -> Result<()> {
        let body = dockerfile_with_options(self.image(), options);
        self.image_build_recipe_with_args(content, tag, &body, platform, &options.build_args)
    }

    /// Run one image build with an explicit recipe and context. The caller
    /// owns temporary exports until this returns; no source Dockerfile is written.
    pub fn image_build_recipe(
        &self,
        content: &Utf8Path,
        tag: &str,
        body: &str,
        platform: Option<ImagePlatform>,
    ) -> Result<()> {
        self.image_build_recipe_with_args(content, tag, body, platform, &[])
    }

    pub fn image_build_recipe_with_args(
        &self,
        content: &Utf8Path,
        tag: &str,
        body: &str,
        platform: Option<ImagePlatform>,
        build_args: &[zellij_core::build_args::BuildArg],
    ) -> Result<()> {
        if platform == Some(ImagePlatform::All) {
            return self.image_publish_recipe(content, tag, body, build_args);
        }
        // Stream the Dockerfile: no temporary file can overwrite authored
        // content or accidentally become part of COPY's build context.
        let mut command = self.runtime().command();
        command
            .args(["build", "-f", "-", "-t", tag])
            .stdin(Stdio::piped());

        if self.runtime().program != "podman" {
            command.args(["--progress", "plain"]);
        }
        if let Some(platform) = platform {
            command.args(["--platform", platform.as_str()]);
        }
        for arg in build_args {
            command.args(["--build-arg", arg.assignment()]);
        }

        command.arg(content.as_str());
        stream_build(&mut command, body).inspect_err(|_| {
            if let Some(platform) = platform {
                zellij_core::diagnosticln!(
                    "Image build for {platform} failed. Check the runtime output: base images must provide this platform, and foreign-architecture RUN steps need a compatible builder or emulation. zel does not install emulators or start services."
                );
            }
        })
    }

    /// Direct registry output avoids Docker's single-platform local image store.
    /// Use the caller's configured builder/connection without creating services.
    fn image_publish_recipe(
        &self,
        content: &Utf8Path,
        tag: &str,
        body: &str,
        build_args: &[zellij_core::build_args::BuildArg],
    ) -> Result<()> {
        let runtime = self.runtime();
        let mut command = runtime.command();
        // Podman appends to an existing manifest. A unique, invocation-owned
        // name prevents stale architectures or a prior partial build leaking in.
        let temporary = tempfile::Builder::new().prefix("zel-multi-").tempdir()?;
        let manifest = format!(
            "zel-multi-{}",
            temporary
                .path()
                .file_name()
                .unwrap()
                .as_encoded_bytes()
                .iter()
                .map(|byte| format!("{byte:02x}"))
                .collect::<String>()
        );
        match runtime.program.as_str() {
            "docker" => {
                if crate::runtime::probe_status(
                    runtime.command().args(["buildx", "version"]),
                    std::time::Duration::from_secs(5),
                ) != crate::runtime::Probe::Ready
                {
                    return Err(Error::InvalidArgument("Multi-platform publication requires Docker Buildx. Install/enable the plugin and select a builder supporting both Linux architectures, then retry; zel does not install or start a builder.".into()));
                }
                command.args([
                    "buildx",
                    "build",
                    "--push",
                    "-t",
                    tag,
                    "--progress",
                    "plain",
                ]);
            }
            "podman" => {
                command.args(["build", "--manifest", &manifest]);
            }
            "nerdctl" => {
                command.args([
                    "build",
                    "--output",
                    &format!("type=image,name={tag},push=true"),
                    "--progress",
                    "plain",
                ]);
            }
            _ => {
                return Err(Error::InvalidArgument(
                    "Combined publication supports Docker, Podman and nerdctl".into(),
                ));
            }
        }
        command.args([
            "-f",
            "-",
            "--platform",
            ImagePlatform::All.build_platforms(),
        ]);
        for arg in build_args {
            command.args(["--build-arg", arg.assignment()]);
        }
        command.arg(content.as_str());
        let result = stream_build(&mut command, body).and_then(|()| {
            if runtime.program == "podman" {
                let status = runtime
                    .command()
                    .args([
                        "manifest",
                        "push",
                        "--all",
                        &manifest,
                        &format!("docker://{tag}"),
                    ])
                    .zel_status()?;
                if !status.success() {
                    return Err(Error::ImageOperationFailed {
                        operation: "manifest push",
                    });
                }
            }
            Ok(())
        });
        if runtime.program == "podman" {
            // Only remove the manifest allocated above, on success or failure.
            // Preserve the actual build/push result if cleanup also fails.
            let cleanup = crate::runtime::probe_status(
                runtime.command().args(["manifest", "rm", &manifest]),
                std::time::Duration::from_secs(5),
            );
            if cleanup != crate::runtime::Probe::Ready {
                zellij_core::diagnosticln!(
                    "Could not remove temporary Podman manifest {manifest}; remove it with `podman manifest rm {manifest}` if it exists."
                );
            }
        }
        if result.is_err() {
            zellij_core::diagnosticln!(
                "Multi-platform build/publication failed. Check registry credentials, base-image architecture support and the selected builder. Foreign RUN steps need emulation or native builder nodes; `zel ci --platform all` generates native-runner builds. No services or emulators were installed."
            );
        }
        result
    }

    /// Run a built image, publishing its port.
    pub fn image_run(&self, tag: &str, port: u16) -> Result<()> {
        let ports = format!("{port}:3000");

        let status = self
            .run_command()
            .args(["--rm", "--init", "-p", &ports, tag])
            .zel_status()?;

        match status.code() {
            Some(0) | Some(130) | None => Ok(()),
            _ => Err(Error::ContentInvalid),
        }
    }

    /// Push a built image, retagging it into `registry` when one is given.
    pub fn image_push(&self, tag: &str, registry: Option<&str>) -> Result<()> {
        let target = match registry {
            Some(registry) => {
                let full = format!("{}/{}", registry.trim_end_matches('/'), tag);
                let status = self
                    .runtime()
                    .command()
                    .args(["tag", tag, &full])
                    .zel_status()?;

                if !status.success() {
                    return Err(Error::ImageOperationFailed { operation: "retag" });
                }
                full
            }
            None => tag.to_owned(),
        };

        let mut command = self.runtime().command();
        command.arg("push");
        // nerdctl otherwise selects the host platform, which may differ from
        // the single-platform image just built. Push the complete local image.
        if self.runtime().program == "nerdctl" {
            command.arg("--all-platforms");
        }
        let status = command.arg(&target).zel_status()?;

        match status.code() {
            Some(0) => Ok(()),
            _ => Err(Error::ImageOperationFailed { operation: "push" }),
        }
    }
}

fn stream_build(command: &mut std::process::Command, body: &str) -> Result<()> {
    let mut child = command.stdin(Stdio::piped()).zel_spawn()?;
    let written = child
        .child
        .stdin
        .take()
        .expect("piped stdin")
        .write_all(body.as_bytes());
    if let Err(error) = written {
        let _ = child.kill();
        let _ = child.wait();
        return Err(error.into());
    }
    match child.wait()?.code() {
        Some(0) => Ok(()),
        _ => Err(Error::BuildFailed),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[cfg(unix)]
    #[test]
    fn streams_dockerfile_without_touching_existing_content_even_on_failure() {
        use std::os::unix::fs::PermissionsExt;
        let temp = tempfile::tempdir().unwrap();
        let root = Utf8Path::from_path(temp.path()).unwrap();
        let content = root.join("content");
        std::fs::create_dir(&content).unwrap();
        std::fs::write(content.join(".zel-dockerfile"), "authored").unwrap();
        let program = root.join("runtime");
        let engine = ContainerEngine::new(
            crate::Runtime {
                program: program.to_string(),
                host: None,
                version: "test".into(),
            },
            "base:test",
        );
        for code in [0, 1] {
            std::fs::write(&program, format!("#!/bin/sh\n[ \"$1 $2 $3\" = 'build -f -' ] || exit 2\ncat > \"$(dirname \"$0\")/received\"\nexit {code}\n")).unwrap();
            std::fs::set_permissions(&program, std::fs::Permissions::from_mode(0o755)).unwrap();
            assert_eq!(
                engine
                    .image_build(&content, "site:test", None, None)
                    .is_ok(),
                code == 0
            );
            assert_eq!(
                std::fs::read_to_string(content.join(".zel-dockerfile")).unwrap(),
                "authored"
            );
            assert_eq!(std::fs::read_dir(&content).unwrap().count(), 1);
            assert_eq!(
                std::fs::read_to_string(root.join("received")).unwrap(),
                dockerfile("base:test", None)
            );
        }
    }

    #[test]
    fn the_runtime_stage_copies_standalone_not_the_whole_build_dependency_tree() {
        let out = dockerfile("ghcr.io/example/zellij-base:latest", None);

        assert!(out.contains("FROM node:24-alpine AS node-runtime"), "{out}");
        assert!(out.contains("FROM scratch AS runtime\nCOPY --from=node-runtime / /"));
        assert!(
            out.contains("/usr/local/lib/node_modules/npm /opt/yarn-v* /usr/local/include/node")
        );
        assert!(!out.contains("COPY --from=build --chown=nextjs:nodejs /app/node_modules"));
        assert!(!out.contains("/opt/zellij AS runtime"));
    }

    #[test]
    fn the_base_image_is_the_one_we_were_given() {
        let out = dockerfile("ghcr.io/acme/mirror:1.2", None);
        assert!(
            out.contains("FROM ghcr.io/acme/mirror:1.2 AS build"),
            "{out}"
        );
    }

    // Features change what `npm install` fetches, so the step has to come
    // before it or it changes nothing at all.
    #[test]
    fn features_are_applied_before_the_install() {
        let out = dockerfile("base:latest", Some("maths,diagrams".parse().unwrap()));

        let features_at = out.find("zellij.mjs features").expect("no features step");
        let install_at = out.find("npm install").expect("no install step");
        assert!(
            features_at < install_at,
            "features must precede install:\n{out}"
        );
        assert!(out.contains("\"maths,diagrams\""), "{out}");
    }

    #[test]
    fn no_features_means_no_step() {
        let out = dockerfile("base:latest", None);
        assert!(!out.contains("zellij.mjs features"), "{out}");
    }

    #[test]
    fn build_arguments_are_names_only_and_do_not_become_runtime_environment() {
        let options = crate::BuildOptions {
            build_args: vec!["PUBLIC_LABEL=日本語 '$(literal)`value`".parse().unwrap()],
            ..Default::default()
        };
        for recipe in [
            dockerfile_with_options("base:test", &options),
            crate::static_image::hosted_with_options("base:test", &options),
        ] {
            let (build, runtime) = recipe.split_once(" AS runtime\n").unwrap();
            assert!(build.contains("ARG PUBLIC_LABEL\n"));
            assert!(
                build.find("ARG PUBLIC_LABEL").unwrap() < build.find("RUN npm install").unwrap()
            );
            assert!(!runtime.contains("PUBLIC_LABEL"));
            assert!(!recipe.contains("日本語") && !recipe.contains("ENV PUBLIC_LABEL"));
        }
        let recipe = crate::static_image::portable_with_args(&options.build_args);
        assert!(recipe.contains("ARG PUBLIC_LABEL\n") && !recipe.contains("日本語"));
        assert!(options.require_no_image_args().is_err());
    }

    // A broken link should fail the image rather than ship inside it.
    #[test]
    fn the_content_is_checked_before_it_is_built() {
        let out = dockerfile("base:latest", None);

        let check_at = out.find("zellij check content").expect("no check step");
        let build_at = out.find("npm run build").expect("no build step");
        assert!(check_at < build_at, "check must precede build:\n{out}");
    }
}
