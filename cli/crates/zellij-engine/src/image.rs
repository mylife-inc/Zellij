//! Turning a content folder into a container image.
//!
//! The Dockerfile is generated rather than kept in the user's repository. The
//! correct one is not obvious — a base image they did not choose, an install
//! step whose shape depends on which features the content uses, and a runtime
//! stage that must copy exactly three paths. Getting it slightly wrong yields
//! an image four times the size that still works, so nothing tells you.
//!
//! It is written to a temporary file and the **content folder is the build
//! context**, so `COPY . /app/content` needs no path arithmetic and no
//! `.dockerignore` of ours.

use camino::Utf8Path;
use std::io::Write;
use zellij_core::{Error, Result};

use crate::ContainerEngine;

/// The multi-stage build for a site image.
///
/// Kept as one string rather than assembled from parts: a Dockerfile somebody
/// may have to read is worth being able to read here too.
pub fn dockerfile(base: &str, features: Option<&str>) -> String {
    let feature_step = match features {
        Some(list) if !list.is_empty() => format!(
            "\n# Before installing, because the point of asking is to change what is fetched.\n\
             RUN node /opt/zellij/bin/zellij.mjs features \"{list}\" /app\n"
        ),
        _ => String::new(),
    };

    format!(
        r#"# Generated by `zel image build`. Regenerate rather than edit: this tracks
# the base image, and a copy that stops tracking it stops being correct.
#
# The build context is the content folder itself.

# --------------------------------------------------------------------- build
FROM {base} AS build

WORKDIR /app

# Replace the placeholder content wholesale, so a file the image had and yours
# does not cannot survive into your site.
RUN rm -rf /app/content
COPY . /app/content/
{feature_step}
# The base image carries the engine and a manifest and nothing else. This is
# where the manifest becomes an installation — deferred to here because it is
# the first moment the content, and so the features it needs, is known.
RUN npm install --install-links --no-audit --no-fund

# Fails the build on a broken link or an invalid section, naming the file,
# rather than publishing a site with a dead page in it.
RUN npx zellij check content

RUN npm run build

# ------------------------------------------------------------------- runtime
FROM node:24-alpine AS runtime

ENV NODE_ENV=production \
    NEXT_TELEMETRY_DISABLED=1 \
    PORT=3000 \
    HOSTNAME=0.0.0.0

# Not root. The site serves pages and needs nothing a user cannot do.
RUN addgroup -g 1001 -S nodejs && adduser -S -u 1001 -G nodejs nextjs

WORKDIR /app

# `standalone` carries its own traced dependencies, so there is no install here
# and no node_modules to ship. Neither is the engine: what you deploy contains
# the compiled site and a Node runtime, and nothing that built it.
COPY --from=build --chown=nextjs:nodejs /app/.next/standalone ./
COPY --from=build --chown=nextjs:nodejs /app/.next/static ./.next/static
COPY --from=build --chown=nextjs:nodejs /app/public ./public

USER nextjs
EXPOSE 3000

HEALTHCHECK --interval=30s --timeout=3s --start-period=5s \
  CMD node -e "fetch('http://127.0.0.1:'+(process.env.PORT||3000)+'/').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))"

CMD ["node", "server.js"]
"#
    )
}

impl ContainerEngine {
    /// Build a site image from `content`.
    pub fn image_build(
        &self,
        content: &Utf8Path,
        tag: &str,
        features: Option<&str>,
        platforms: Option<&str>,
    ) -> Result<()> {
        let body = dockerfile(self.image(), features);

        // Beside the content rather than in /tmp: Docker reads the Dockerfile
        // through the same daemon that reads the context, and on a machine
        // where /tmp is not shared with the runtime's virtual machine, a
        // Dockerfile in /tmp is a file the daemon cannot see.
        let path = content.join(".zel-dockerfile");
        let mut file = std::fs::File::create(&path)?;
        file.write_all(body.as_bytes())?;
        drop(file);

        let mut command = self.runtime().command();
        command
            .args(["build", "-f", path.as_str(), "-t", tag])
            .args(["--progress", "plain"]);

        if let Some(platforms) = platforms {
            command.args(["--platform", platforms]);
        }

        let status = command.arg(content.as_str()).status();

        // Whatever happened, the generated file does not belong in somebody's
        // content folder afterwards.
        let _ = std::fs::remove_file(&path);

        match status?.code() {
            Some(0) => Ok(()),
            _ => Err(Error::ContentInvalid),
        }
    }

    /// Run a built image, publishing its port.
    pub fn image_run(&self, tag: &str, port: u16) -> Result<()> {
        let ports = format!("{port}:3000");

        let status = self
            .runtime()
            .command()
            .args(["run", "--rm", "--init", "-p", &ports, tag])
            .status()?;

        match status.code() {
            Some(0) | Some(130) | None => Ok(()),
            _ => Err(Error::ContentInvalid),
        }
    }

    /// Push a built image, retagging it into `registry` when one is given.
    pub fn image_push(&self, tag: &str, registry: Option<&str>) -> Result<()> {
        let target = match registry {
            Some(registry) => {
                let full = format!("{}/{}", registry.trim_end_matches('/'), tag);
                let status = self
                    .runtime()
                    .command()
                    .args(["tag", tag, &full])
                    .status()?;

                if !status.success() {
                    return Err(Error::ContentInvalid);
                }
                full
            }
            None => tag.to_owned(),
        };

        let status = self.runtime().command().args(["push", &target]).status()?;

        match status.code() {
            Some(0) => Ok(()),
            _ => Err(Error::ContentInvalid),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_runtime_stage_carries_neither_the_engine_nor_node_modules() {
        let out = dockerfile("ghcr.io/example/zellij-base:latest", None);

        assert!(out.contains("FROM node:24-alpine AS runtime"), "{out}");
        assert!(!out.contains("COPY --from=build --chown=nextjs:nodejs /app/node_modules"));
        assert!(!out.contains("/opt/zellij AS runtime"));
    }

    #[test]
    fn the_base_image_is_the_one_we_were_given() {
        let out = dockerfile("ghcr.io/acme/mirror:1.2", None);
        assert!(
            out.contains("FROM ghcr.io/acme/mirror:1.2 AS build"),
            "{out}"
        );
    }

    // Features change what `npm install` fetches, so the step has to come
    // before it or it changes nothing at all.
    #[test]
    fn features_are_applied_before_the_install() {
        let out = dockerfile("base:latest", Some("maths,diagrams"));

        let features_at = out.find("zellij.mjs features").expect("no features step");
        let install_at = out.find("npm install").expect("no install step");
        assert!(
            features_at < install_at,
            "features must precede install:\n{out}"
        );
        assert!(out.contains("\"maths,diagrams\""), "{out}");
    }

    #[test]
    fn no_features_means_no_step() {
        let out = dockerfile("base:latest", None);
        assert!(!out.contains("zellij.mjs features"), "{out}");
    }

    // A broken link should fail the image rather than ship inside it.
    #[test]
    fn the_content_is_checked_before_it_is_built() {
        let out = dockerfile("base:latest", None);

        let check_at = out.find("zellij check content").expect("no check step");
        let build_at = out.find("npm run build").expect("no build step");
        assert!(check_at < build_at, "check must precede build:\n{out}");
    }
}
