//! Static image recipes. Portable input is an already generated HTML export;
//! hosted input is content compiled inside the builder stage. Only HTML and
//! its public assets reach the final image, which runs NGINX without root.

// Only NGINX core is needed for static files; omit the optional dynamic modules
// and their image-processing/XML dependencies from the ordinary Alpine variant.
pub const STATIC_BASE: &str = "nginxinc/nginx-unprivileged:stable-alpine-slim";

fn runtime(copy: &str, health: &str, build_args: &str) -> String {
    format!(
        r#"FROM {STATIC_BASE} AS runtime
{build_args}USER root
RUN rm -rf /usr/share/nginx/html/* && printf '%s\n' \
    'server {{' \
    '  listen 3000;' \
    '  listen [::]:3000;' \
    '  server_name _;' \
    '  root /usr/share/nginx/html;' \
    '  index index.html;' \
    '  absolute_redirect off;' \
    '  location ~ (^|/)\.zellij-output$ {{ return 404; }}' \
    '  location / {{ try_files $uri $uri.html $uri/ =404; }}' \
    '}}' > /etc/nginx/conf.d/default.conf
{copy}
{health}
USER nginx
EXPOSE 3000
HEALTHCHECK --interval=30s --timeout=3s --start-period=5s \
  CMD wget -q -O /dev/null "http://127.0.0.1:3000$(cat /etc/zellij-health-path)" || exit 1
CMD ["nginx", "-g", "daemon off;"]
"#
    )
}

/// Package a native export. The caller generates it first, in an isolated
/// temporary directory; this recipe never copies the Markdown source.
pub fn portable() -> String {
    portable_with_args(&[])
}

pub fn portable_with_args(args: &[zellij_core::build_args::BuildArg]) -> String {
    format!(
        "# Generated by `zel image dockerfile --kind static` for portable Markdown.\n\
         # First run `zel build`; the build context must be the generated HTML\n\
         # output folder (site/ by default), NOT the source or site root.\n\n{}",
        runtime(
            "COPY --chown=nginx:nginx . /usr/share/nginx/html/",
            "RUN printf '%s\\n' '/index.html' > /etc/zellij-health-path",
            &zellij_core::build_args::declarations(args),
        )
    )
}

/// Build and package a hosted export without bind mounts. The engine resolves
/// basePath with the same code used by Next; the export is mounted at that
/// prefix in the final server, including Next assets and JSON search data.
pub fn hosted(base: &str, features: Option<zellij_core::features::Features>) -> String {
    hosted_with_options(base, &crate::BuildOptions::with_features(features))
}

pub fn hosted_with_options(base: &str, options: &crate::BuildOptions) -> String {
    let feature_step = options
        .features
        .map(|features| format!("RUN {}\n", crate::image::feature_command(features)))
        .unwrap_or_default();
    let overrides = options.docker_environment();
    let guard = options.docker_guard();
    let check = options.docker_check();
    let build_args = zellij_core::build_args::declarations(&options.build_args);
    format!(
        r#"# Generated by `zel image dockerfile --kind static` for hosted content.
# The build context is the content folder (content/ in a configured site).
FROM {base} AS build
{build_args}WORKDIR /app
ENV ZELLIJ_OUTPUT=export
{overrides}{guard}
RUN rm -rf /app/content
COPY . /app/content/
{feature_step}RUN npm install --install-links --no-audit --no-fund
{check}
RUN npm run build
# Next exports paths relative to its deployment root. Keep the deployment
# prefix when copying to the HTTP root; never interpolate it into shell code.
RUN node -e "const fs = require('node:fs'); const p = require('./node_modules/@shebka/zellij/deployment-config.cjs').resolveContentLocation().basePath || ''; fs.mkdirSync('/publish' + p, {{recursive:true}}); fs.cpSync('/app/out', '/publish' + p, {{recursive:true}}); fs.writeFileSync('/zellij-health-path', encodeURI(p) + '/index.html');"

{}"#,
        runtime(
            "COPY --from=build --chown=nginx:nginx /publish/ /usr/share/nginx/html/",
            "COPY --from=build /zellij-health-path /etc/zellij-health-path",
            "",
        )
    )
}
