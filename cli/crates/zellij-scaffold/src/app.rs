//! One wrapper template shared with the engine's Node initializer and images.
use crate::{DocsOptions, Scaffold};
use serde_json::{Value, json};
use zellij_core::{Error, Result, yaml};

pub fn template() -> Value {
    serde_json::from_str(include_str!("../generated/app.json"))
        .expect("the committed engine wrapper template is valid JSON")
}

pub struct AppOptions<'a> {
    pub name: &'a str,
    pub engine_dependency: &'a str,
    pub content: &'a str,
    pub port: u16,
    pub features: &'a [String],
    pub with_docs: bool,
}

fn package_name(name: &str) -> String {
    let mut result = String::new();
    for ch in name.chars().take(214) {
        if ch.is_ascii_alphanumeric() {
            result.push(ch.to_ascii_lowercase());
        } else if !result.ends_with('-') {
            result.push('-');
        }
    }
    let name = result.trim_matches('-');
    if name.is_empty() {
        "zellij-app".into()
    } else {
        name.into()
    }
}

pub fn app(options: &AppOptions<'_>) -> Result<Scaffold> {
    if options.name.trim().is_empty() || options.name.chars().any(char::is_control) {
        return Err(Error::InvalidArgument(
            "app name must be nonempty text without control characters".into(),
        ));
    }
    if options.port == 0 {
        return Err(Error::InvalidArgument(
            "app port must be between 1 and 65535; pass --port to override preview.port".into(),
        ));
    }
    let template = template();
    let mut manifest = template["manifest"].clone();
    manifest["name"] = json!(package_name(options.name));
    manifest["dependencies"]["@shebka/zellij"] = json!(options.engine_dependency);
    for value in manifest["scripts"].as_object_mut().unwrap().values_mut() {
        *value = json!(
            value
                .as_str()
                .unwrap()
                .replace("__ZELLIJ_PORT__", &options.port.to_string())
        );
    }
    let available = template["features"].as_object().unwrap();
    for feature in options.features {
        let names: Vec<_> = if feature == "all" {
            available.keys().map(String::as_str).collect()
        } else {
            vec![feature.as_str()]
        };
        for name in names {
            let deps = available.get(name).ok_or_else(|| {
                Error::InvalidArgument("unknown app feature; choose maths, diagrams or all".into())
            })?;
            manifest["dependencies"]
                .as_object_mut()
                .unwrap()
                .extend(deps.as_object().unwrap().clone());
        }
    }
    let mut scaffold = Scaffold::new();
    for (path, body) in template["files"].as_object().unwrap() {
        scaffold.add(path.as_str(), body.as_str().unwrap());
    }
    scaffold.add(
        "package.json",
        format!("{}\n", serde_json::to_string_pretty(&manifest).unwrap()),
    );
    scaffold.add(
        "zellij.config.yaml",
        format!(
            "# Wrapper content location; presentation remains in the selected site.\nversion: 1\ncontent: {}\n",
            yaml::string(options.content)
        ),
    );
    scaffold.add(
        "README.md",
        format!(
            r#"# Zellij wrapper

This app references the hosted content selected in `zellij.config.yaml`.
Edit that content to change the site; `src/app/` holds the editable Next.js wrapper.

## Run the app

Install Node matching `package.json`'s engines field, then run:

```sh
npm install
npm run check
npm run dev
```

The development server uses port {}. `npm run build` creates a production build;
`npm start` serves it. Optional maths/diagram packages are listed in package.json.

The engine is a local file dependency because it is not published to npm.
Use a built engine package from the matching Zellij checkout. If you move the
engine, update its dependency in package.json and reinstall. If you move external
content, update zellij.config.yaml. The source content is referenced, not copied.

Scaffolding installs nothing and does not start a server. The hosted renderer
needs HTTP serving. Portable Markdown's direct-file output remains available
through `zel build` with the portable renderer.

Generated by `zel new app` with engine template {}.
"#,
            options.port,
            template["engineVersion"].as_str().unwrap()
        ),
    );
    if options.with_docs {
        for (path, body) in crate::configured_docs(&DocsOptions {
            name: options.name.into(),
            theme: "cupertino".into(),
            guide: true,
            minimal: false,
        })
        .files()
        {
            scaffold.add(format!("docs/zellij/{path}"), body);
        }
    }
    Ok(scaffold)
}
