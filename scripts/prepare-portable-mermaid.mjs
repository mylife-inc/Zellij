// Generate a single classic script: ES modules/chunks cannot load via file://.
// Cargo embeds committed output; Node is only a maintainer/CI dependency.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build, version as esbuild } from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
process.chdir(root);
const destination = 'cli/crates/zellij-docs/assets/mermaid';
const sha = text => createHash('sha256').update(text).digest('hex');
const json = async file => JSON.parse(await readFile(file, 'utf8'));
const embedded = await json(`${destination}/embedded-notices.json`);
const yamlChunk = 'node_modules/mermaid/dist/chunks/mermaid.core/chunk-LNGE3PJU.mjs';
const yamlHash = '2cb4e5f8d5fd99daccb0135fda6a5583c91f39efb0bb845af9d968ed427efcb2';
assert.equal(sha(await readFile(yamlChunk)), yamlHash, 'Review the upstream YAML shim after upgrading Mermaid');
assert.equal((await json('node_modules/js-yaml/package.json')).version, '4.3.2');
let replaced = false;
const bundle = await build({
  entryPoints: ['cli/crates/zellij-docs/assets/mermaid-client.js'],
  bundle: true, platform: 'browser', format: 'iife', target: 'es2022',
  minify: true, metafile: true, write: false, legalComments: 'eof',
  plugins: [{
    name: 'patched-yaml',
    setup(build) {
      build.onLoad({ filter: /chunk-LNGE3PJU\.mjs$/ }, async ({ path: file }) => {
        assert.equal(sha(await readFile(file)), yamlHash);
        replaced = true;
        // Upstream bundles js-yaml 4.3.0; npm overrides cannot replace it.
        return { contents: 'export { JSON_SCHEMA, load } from "js-yaml";', resolveDir: root };
      });
    },
  }],
});
assert(replaced, 'The embedded YAML parser must be replaced');
assert.equal(bundle.outputFiles.length, 1);
for (const output of Object.values(bundle.metafile.outputs)) assert.deepEqual(output.imports, []);

const packageRoots = new Set();
const sources = [];
const vendors = new Set();
const oldLodashFiles = new Set();
for (const file of Object.keys(bundle.metafile.inputs).sort()) {
  const normalized = file.replaceAll('\\', '/');
  const match = normalized.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)/);
  if (match) packageRoots.add(match[1]);
  sources.push([normalized, sha(await readFile(file))]);
  if (normalized === yamlChunk) continue; // Its original code is not bundled.
  let map;
  try { map = await json(`${file}.map`); } catch (error) { if (error.code === 'ENOENT') continue; throw error; }
  sources.push([`${normalized}.map`, sha(await readFile(`${file}.map`))]);
  for (const [i, source] of map.sources.entries()) {
    const vendor = source.match(/\.pnpm\/([^/]+)\//)?.[1];
    if (vendor) vendors.add(vendor.split('_')[0]);
    if (vendor === 'lodash-es@4.17.23') oldLodashFiles.add(path.posix.basename(source));
    if (source.includes('node_modules/path-browserify/')) {
      assert.equal(sha(map.sourcesContent[i]), 'f6d60f9e7cd83f65f947cda34ef846e82706c044d9a9fa7c5b69718b13b78e28');
      vendors.add('path-browserify@1.0.1');
    }
  }
}
// The parser contains a subset of 4.17.23, but none of the functions affected
// by GHSA-r5fr-rjxr-66jc / GHSA-f23m-r3pf-42rh. Fail closed if that changes.
assert(oldLodashFiles.size > 0);
for (const file of ['template.js', 'templateSettings.js', 'unset.js', 'omit.js', '_baseUnset.js']) {
  assert(!oldLodashFiles.has(file), `Vulnerable embedded Lodash function: ${file}`);
}
assert.deepEqual([...vendors].sort(), embedded.map(p => `${p.name.replace('/', '+')}@${p.version}`).sort(),
  'Review embedded dependencies and obtain their exact-version notices after an upstream change');

const packages = [];
let licenses = 'Portable Mermaid runtime — third-party notices\nGenerated by scripts/prepare-portable-mermaid.mjs\n';
for (const directory of [...packageRoots].sort()) {
  const pkg = await json(`${directory}/package.json`);
  packages.push({ name: pkg.name, version: pkg.version });
  licenses += `\n\n===== ${pkg.name} ${pkg.version} =====\n`;
  const names = (await readdir(directory)).filter(n => /^(licen[sc]e|copying|notice)(\.|$)/i.test(n)).sort();
  if (pkg.name === 'fastdom') {
    const readme = await readFile(`${directory}/README.md`, 'utf8');
    assert(readme.includes('## License'));
    licenses += readme.slice(readme.indexOf('## License'));
  } else {
    assert(names.length, `Missing license: ${pkg.name}`);
    for (const name of names) licenses += `\n${name}\n${await readFile(`${directory}/${name}`, 'utf8')}\n`;
  }
}
for (const p of embedded) {
  licenses += `\n\n===== ${p.name} ${p.version} (embedded upstream) =====\n${p.tarball}\n`;
  for (const notice of p.notices) licenses += `\n${notice.file}\n${notice.text}\n`;
}
licenses = licenses.replaceAll('\r\n', '\n').trimEnd() + '\n';
const script = `/* Generated by scripts/prepare-portable-mermaid.mjs. See licenses.txt and manifest.json. */\n${bundle.outputFiles[0].text}`;
const manifest = JSON.stringify({
  generator: 'scripts/prepare-portable-mermaid.mjs', esbuild,
  sha256: sha(script), sourceGraphSha256: sha(JSON.stringify(sources)),
  packages, embedded: embedded.map(({ name, version, integrity }) => ({ name, version, integrity })),
  replaced: { file: yamlChunk, sha256: yamlHash, with: 'js-yaml@4.3.2' },
  reviewedLodashSubset: [...oldLodashFiles].sort(),
}, null, 2) + '\n';
for (const [name, expected] of Object.entries({ 'mermaid.js': script, 'licenses.txt': licenses, 'manifest.json': manifest })) {
  const file = `${destination}/${name}`;
  if (process.argv.includes('--write')) await writeFile(file, expected);
  else assert.equal((await readFile(file, 'utf8')).replaceAll('\r\n', '\n'), expected,
    `${name} is stale. Run node scripts/prepare-portable-mermaid.mjs --write`);
}
console.log(`Portable Mermaid: ${Buffer.byteLength(script)} bytes; local IIFE, patched YAML, ${packages.length} package notices and ${embedded.length} embedded notices verified.`);
