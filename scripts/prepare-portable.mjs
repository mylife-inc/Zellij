// One token definition for hosted and portable documentation. Native Cargo
// builds use the committed stylesheet without Node.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const path = new URL('../cli/crates/zellij-docs/assets/themes.css', import.meta.url);
const bundle = await build({
  stdin: {
    contents: `import { emitThemeCss } from './engine/packages/zellij/src/themes/emit';
      import { siteConfigSchema } from './engine/packages/zellij/src/config/schema';
      export const css = emitThemeCss(siteConfigSchema.parse({ name: 'Portable documentation', nav: { themeSwitcher: true } }));`,
    resolveDir: fileURLToPath(new URL('../', import.meta.url)),
  }, bundle: true, platform: 'node', format: 'esm', write: false,
});
const { css } = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].contents).toString('base64')}`);
const expected = `/* Generated by scripts/prepare-portable.mjs from the engine theme tokens. */\n${css}\n`;
if (process.argv.includes('--write')) {
  await writeFile(path, expected);
} else if ((await readFile(path, 'utf8')).replaceAll('\r\n', '\n') !== expected) {
  throw new Error('Portable theme tokens are stale. Run node scripts/prepare-portable.mjs --write');
}
