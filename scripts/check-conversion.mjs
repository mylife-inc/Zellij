    await write('docs/02-Setup/_category_.yaml', 'label: Setup navigation\nposition: 2.5\nlink:\n  type: generated-index\n  title: Setup overview\n  slug: Sections/Setup\n  description: Build <docs> {safely} & [quickly]\n');
