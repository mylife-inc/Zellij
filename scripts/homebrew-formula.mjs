// Generate the owned tap's formula from one immutable release checksum inventory.
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { releasePolicy } from './release-policy.mjs';

export function homebrewFormula(tag, checksums) {
  const { version, prerelease } = releasePolicy(tag);
  const entries = new Map();
  for (const line of checksums.split(/\r?\n/).filter(line => line.trim())) {
    const match = /^([a-fA-F0-9]{64})\s+\*?(?:\.\/)?([^\s]+)$/.exec(line);
    if (!match || entries.has(match[2])) throw new Error('Malformed or duplicate release checksum entry');
    entries.set(match[2], match[1].toLowerCase());
  }
  const asset = (target, indent) => {
    const name = `zel-${tag}-${target}.tar.gz`;
    const digest = entries.get(name);
    if (!digest) throw new Error(`Missing checksum for ${name}`);
    const spaces = ' '.repeat(indent);
    return `${spaces}url "https://github.com/mylife-inc/releases/releases/download/zellij-${tag}/${name}"\n${spaces}sha256 "${digest}"`;
  };
  return `# Generated by Zellij scripts/homebrew-formula.mjs; update from verified release checksums.
class Zel < Formula
  desc "Build portable documentation and product websites with Zellij"
  homepage "https://zellij.shebka.net"
  version "${version}"
  license :cannot_represent

  on_macos do
    on_arm do
${asset('aarch64-apple-darwin', 6)}
    end
    on_intel do
${asset('x86_64-apple-darwin', 6)}
    end
  end

  on_linux do
    on_arm do
${asset('aarch64-unknown-linux-gnu', 6)}
    end
    on_intel do
${asset('x86_64-unknown-linux-gnu', 6)}
    end
  end

  livecheck do
    skip "Updated from verified Zellij releases"
  end

  def install
    bin.install "zel"
    (share/"zel").mkpath
    (share/"zel/installation-manager").write "homebrew\\n"
    generate_completions_from_executable(bin/"zel", "completions")
  end

  def caveats
    <<~EOS
      ${prerelease ? `This installs development preview ${version}.` : `This installs Zellij ${version}.`}
      Update with: brew upgrade mylife-inc/tap/zel
      Portable Markdown builds need no container runtime.
      Hosted builds use the matching engine image:
        export ZELLIJ_IMAGE=ghcr.io/mylife-inc/zellij-base:${version}
    EOS
  end

  test do
    assert_equal "zel #{version}\\n", shell_output("#{bin}/zel --version")
    assert_match "brew upgrade mylife-inc/tap/zel", shell_output("#{bin}/zel upgrade --preview 2>&1", 1)
    system bin/"zel", "new", "portable", "manual", "--name", "Homebrew acceptance"
    system bin/"zel", "build", "manual"
    assert_path_exists testpath/"manual/site/index.html"
    assert_match "Homebrew acceptance", (testpath/"manual/site/index.html").read
  end
end
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.length !== 4) throw new Error('Usage: homebrew-formula.mjs <version> <SHA256SUMS>');
    process.stdout.write(homebrewFormula(process.argv[2], readFileSync(process.argv[3], 'utf8')));
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
