// Generate the owned bucket's manifest from immutable release checksums.
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { releasePolicy } from './release-policy.mjs';

export function scoopManifest(tag, checksums) {
  const { version, prerelease } = releasePolicy(tag);
  const entries = new Map();
  for (const line of checksums.split(/\r?\n/).filter(line => line.trim())) {
    const match = /^([a-fA-F0-9]{64})\s+\*?(?:\.\/)?([^\s]+)$/.exec(line);
    if (!match || entries.has(match[2])) throw new Error('Malformed or duplicate release checksum entry');
    entries.set(match[2], match[1].toLowerCase());
  }
  const asset = target => {
    const name = `zel-${tag}-${target}.zip`;
    const hash = entries.get(name);
    if (!hash) throw new Error(`Missing checksum for ${name}`);
    return { url: `https://github.com/mylife-inc/releases/releases/download/zellij-${tag}/${name}`, hash };
  };
  return {
    '##': 'Generated by Zellij scripts/scoop-manifest.mjs from verified release checksums.',
    version,
    description: 'Build portable documentation and product websites with Zellij',
    homepage: 'https://zellij.shebka.net',
    license: 'Proprietary',
    architecture: {
      '64bit': asset('x86_64-pc-windows-msvc'),
      arm64: asset('aarch64-pc-windows-msvc'),
    },
    extract_to: 'bin',
    bin: 'bin\\zel.exe',
    post_install: [
      "$share = New-Item -ItemType Directory -Force (Join-Path $dir 'share\\zel')",
      // Exact LF bytes, with no Windows PowerShell 5.1 UTF-8 BOM.
      '[System.IO.File]::WriteAllText((Join-Path $share.FullName \'installation-manager\'), "scoop`n", [System.Text.UTF8Encoding]::new($false))',
    ],
    notes: [
      prerelease ? `This installs development preview ${version}.` : `This installs Zellij ${version}.`,
      'Update with: scoop update zel',
      'Portable Markdown builds need no container runtime.',
      `For hosted builds, select the matching engine: $env:ZELLIJ_IMAGE = 'ghcr.io/mylife-inc/zellij-base:${version}'`,
    ],
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.length !== 4) throw new Error('Usage: scoop-manifest.mjs <version> <SHA256SUMS>');
    process.stdout.write(JSON.stringify(scoopManifest(process.argv[2], readFileSync(process.argv[3], 'utf8')), null, 4) + '\n');
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
