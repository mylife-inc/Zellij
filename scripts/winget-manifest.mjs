// WinGet's three-file manifest, generated from immutable release checksums.
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { releasePolicy } from './release-policy.mjs';

export const wingetId = 'Shebka.Zel';
export function wingetManifests(tag, checksums) {
  const { version, prerelease } = releasePolicy(tag);
  const [core, preview] = version.split('-');
  const parts = core.split('.').map(BigInt);
  const newerCore = parts[0] > 0n || parts[1] > 2n || (parts[1] === 2n && parts[2] > 0n);
  const supportedCore = parts[0] === 0n && parts[1] === 2n && parts[2] === 0n;
  if (!(newerCore || (supportedCore && (!preview || /^rc\.\d+$/.test(preview) && BigInt(preview.slice(3)) >= 15n)))) {
    throw new Error('WinGet ownership protection requires CLI v0.2.0-rc.15 or newer');
  }
  const hashes = new Map();
  for (const line of checksums.split(/\r?\n/).filter(line => line.trim())) {
    const match = /^([a-fA-F0-9]{64})\s+\*?(?:\.\/)?([^\s]+)$/.exec(line);
    if (!match || hashes.has(match[2])) throw new Error('Malformed or duplicate release checksum entry');
    hashes.set(match[2], match[1].toUpperCase());
  }
  const common = { PackageIdentifier: wingetId, PackageVersion: version };
  const schema = { ManifestVersion: '1.28.0' };
  const installers = [['x64', 'x86_64-pc-windows-msvc'], ['arm64', 'aarch64-pc-windows-msvc']].map(([arch, target]) => {
    const name = `zel-${tag}-${target}.zip`, hash = hashes.get(name);
    if (!hash) throw new Error(`Missing checksum for ${name}`);
    return { Architecture: arch, InstallerUrl: `https://github.com/mylife-inc/releases/releases/download/zellij-${tag}/${name}`, InstallerSha256: hash };
  });
  return {
    [`${wingetId}.yaml`]: { ...common, DefaultLocale: 'en-US', ManifestType: 'version', ...schema },
    [`${wingetId}.installer.yaml`]: {
      ...common, InstallerType: 'zip', NestedInstallerType: 'portable',
      NestedInstallerFiles: [{ RelativeFilePath: 'zel.exe', PortableCommandAlias: 'zel' }],
      Commands: ['zel'], UpgradeBehavior: 'install',
      Installers: installers, ManifestType: 'installer', ...schema,
    },
    [`${wingetId}.locale.en-US.yaml`]: {
      ...common, PackageLocale: 'en-US', Publisher: 'Shebka LLC',
      PublisherUrl: 'https://shebka.net', PackageName: 'Zellij CLI',
      PackageUrl: 'https://zellij.shebka.net', License: 'Proprietary',
      ShortDescription: 'Build rich, offline documentation and product websites with the zel CLI.',
      Description: `Zellij turns Markdown and YAML into documentation and product websites. Rich double-clickable sites use a verified renderer downloaded on first use and cached under ZELLIJ_HOME. Docker, Node.js and Python are not required for rich file build, check, watch or view. See the documentation for development, PDF and container requirements.${prerelease ? ` This is development preview ${version}.` : ''}`,
      Tags: ['documentation', 'markdown', 'static-site-generator', 'offline'],
      ReleaseNotesUrl: `https://github.com/mylife-inc/releases/releases/tag/zellij-${tag}`,
      ManifestType: 'defaultLocale', ...schema,
    },
  };
}

// JSON is a YAML subset. Emit block YAML with quoted strings so release values
// cannot become YAML tags, anchors or duplicate keys; no external dependency.
export function manifestYaml(document) {
  function render(value, depth) {
    const indent = ' '.repeat(depth);
    if (Array.isArray(value)) return value.map(item => typeof item === 'object'
      ? `${indent}-\n${render(item, depth + 2)}` : `${indent}- ${JSON.stringify(item)}\n`).join('');
    return Object.entries(value).map(([key, item]) => typeof item === 'object'
      ? `${indent}${key}:\n${render(item, depth + 2)}` : `${indent}${key}: ${JSON.stringify(item)}\n`).join('');
  }
  return `# Generated by Zellij scripts/winget-manifest.mjs\n# yaml-language-server: $schema=https://aka.ms/winget-manifest.${document.ManifestType}.${document.ManifestVersion}.schema.json\n${render(document, 0)}`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const [tag, sums, output] = process.argv.slice(2);
    if (!tag || !sums || !output || process.argv.length !== 5) throw new Error('Usage: winget-manifest.mjs <version> <SHA256SUMS> <new-output-directory>');
    const documents = wingetManifests(tag, await readFile(sums, 'utf8'));
    await mkdir(output); // Do not replace an existing reviewed manifest set.
    for (const [name, document] of Object.entries(documents)) await writeFile(path.join(output, name), manifestYaml(document), { flag: 'wx' });
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
